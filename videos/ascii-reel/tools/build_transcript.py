"""Map ASR word times (source timeline) through the pause-edit map + tempo into the final timeline,
apply manual text corrections, group into caption phrases, emit a TS data module.

usage: build_transcript.py asr_word.json editmap.json tempo out.ts
"""
import json
import sys

asr_p, map_p, tempo, out_p = sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4]
direct_p = sys.argv[5] if len(sys.argv) > 5 else None  # ASR run directly on the final audio
final_f32 = sys.argv[6] if len(sys.argv) > 6 else None
chunks = json.load(open(asr_p))["chunks"]
segs = json.load(open(map_p))["segments"]


def map_t(t, is_start):
    for s in segs:
        if s["src"] <= t <= s["src_end"]:
            return (s["dst"] + (t - s["src"])) / tempo
    # inside a removed gap: starts snap forward, ends snap back
    if is_start:
        nxt = [s for s in segs if s["src"] > t]
        return (nxt[0]["dst"] if nxt else segs[-1]["dst"] + segs[-1]["src_end"] - segs[-1]["src"]) / tempo
    prv = [s for s in segs if s["src_end"] < t]
    s = prv[-1]
    return (s["dst"] + s["src_end"] - s["src"]) / tempo


fix = {
    23: "21-м", 27: "22-м", 32: "Google", 51: "есть", 91: "денюжку —", 93: "всё", 97: "$#%@!",
    98: "Я", 99: "сейчас,", 100: "значит,", 104: "RuStore,", 107: "такой:", 110: "ли", 112: "Контакт",
    114: "таковой,", 121: "нужен?", 124: "туда,", 129: "Контакт.", 130: "Чего",
}
merge = {63: 64, 89: 90}  # "что"+"-нибудь", "какую"+"-то"

words = []
skip = set(merge.values())
for i, c in enumerate(chunks):
    if i in skip:
        continue
    s, e = c["timestamp"]
    text = fix.get(i, c["text"].strip())
    if i in merge:
        j = merge[i]
        text = text + chunks[j]["text"].strip()
        e = chunks[j]["timestamp"][1]
    words.append({"i": i, "text": text, "start": round(map_t(s, True), 3), "end": round(map_t(e, False), 3)})

# prefer timings from ASR run directly on the final audio where the word sequences align
if direct_p:
    import difflib
    import re

    def norm(t):
        return re.sub(r"[^а-яёa-z0-9]", "", t.lower().replace("ё", "е"))

    direct = json.load(open(direct_p))["chunks"]
    a = [norm(chunks[w["i"]]["text"]) for w in words]
    b = [norm(c["text"]) for c in direct]
    sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
    n_fix = 0
    for blk in sm.get_matching_blocks():
        for k in range(blk.size):
            w, d = words[blk.a + k], direct[blk.b + k]
            ds, de = d["timestamp"]
            if abs(ds - w["start"]) < 1.5:
                w["start"] = round(ds, 3)
                if de:
                    w["end"] = round(de, 3)
                n_fix += 1
    print("direct-aligned words:", n_fix, "/", len(words))
    # enforce monotonic starts
    for k in range(1, len(words)):
        if words[k]["start"] < words[k - 1]["start"]:
            words[k]["start"] = words[k - 1]["start"] + 0.05

# snap word starts that follow a pause to the actual speech onset (energy)
if final_f32:
    import numpy as np
    x = np.fromfile(final_f32, dtype=np.float32)
    hop = 480
    fr = x[: len(x) // hop * hop].reshape(-1, hop)
    db = 10 * np.log10((fr ** 2).mean(1) + 1e-12)
    speech = db > -42
    for w in words:
        c = int(w["start"] * 100)
        lo, hi = max(1, c - 25), min(len(db) - 1, c + 25)
        onsets = [j for j in range(lo, hi) if speech[j] and not speech[j - 1:j].any() and not speech[max(0, j - 8):j].any()]
        if onsets:
            j = min(onsets, key=lambda j: abs(j - c))
            w["start"] = round(j / 100, 3)

# keep word durations sane: cap very long words (DTW tends to swallow pauses)
for k, w in enumerate(words):
    nxt = words[k + 1]["start"] if k + 1 < len(words) else w["end"]
    w["end"] = round(min(w["end"], nxt, w["start"] + 0.9), 3)
    if w["end"] <= w["start"]:
        w["end"] = round(w["start"] + 0.12, 3)

# phrase groups by original ASR index ranges (inclusive)
groups = [(0, 3), (4, 8), (9, 11), (12, 17), (18, 24), (25, 29), (30, 36), (37, 41), (42, 46), (47, 54),
          (55, 58), (59, 65), (66, 69), (70, 77), (78, 82), (83, 88), (89, 91), (92, 97), (98, 104),
          (105, 112), (113, 121), (122, 129), (130, 132)]
phrases = []
for a, b in groups:
    idx = [k for k, w in enumerate(words) if a <= w["i"] <= b]
    phrases.append({"from": idx[0], "to": idx[-1], "start": words[idx[0]]["start"], "end": words[idx[-1]]["end"]})

src_idx = {w["i"]: k for k, w in enumerate(words)}
with open(out_p, "w") as f:
    f.write("// generated by build_transcript.py — final-timeline word timings (seconds)\n")
    f.write("export type Word = {i: number; text: string; start: number; end: number};\n")
    f.write("export type Phrase = {from: number; to: number; start: number; end: number};\n")
    f.write("export const WORDS: Word[] = " + json.dumps(words, ensure_ascii=False) + ";\n")
    f.write("export const PHRASES: Phrase[] = " + json.dumps(phrases) + ";\n")
    f.write("// ASR index -> WORDS index (story cues are keyed by ASR index)\n")
    f.write("export const SRC_INDEX: Record<number, number> = " + json.dumps(src_idx) + ";\n")
for p in phrases:
    print(f'{p["start"]:6.2f}-{p["end"]:6.2f}  ' + " ".join(words[k]["text"] for k in range(p["from"], p["to"] + 1)))
